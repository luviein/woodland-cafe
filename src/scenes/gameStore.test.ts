  expect(loaded.state.stock).toEqual(checkpoint.stock);
  expect(getGameState(owner).leaves).toBe(785);
  endCafeDay(owner);
  expect(loadGame(slot.read()!)).toEqual({ ok: true, state: getGameState(owner) });
