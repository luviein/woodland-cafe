it('persists ticket purchases without committing cafe-day earnings or consumption', () => {
  const values = new Map<string, unknown>();
  const owner = { registry: { get: (key: string) => values.get(key), set: (key: string, value: unknown) => values.set(key, value) } } as unknown as Phaser.Game;
  const slot = memorySaveSlot();
  initGameState(owner, slot);
  const checkpoint = { ...createNewGame(), christmasTickets: 1000 };
  continueGame(owner, checkpoint);
  beginCafeDay(owner);
  setGameState(owner, { ...checkpoint, day: 2, leaves: 999, stock: { ...checkpoint.stock, mushroom: 1 } });
  const purchases: CatalogueItem[] = ['christmasTree', 'christmasTree', 'redCape', FINISH_IDS[0]];
  for (const id of purchases) purchaseChristmasItem(owner, id);
  const saved = loadGame(slot.read()!);
  expect(saved.ok).toBe(true);
  if (!saved.ok) return;
  expect(saved.state.christmasTickets).toBe(1000 - purchases.reduce((sum, id) => sum + catalogueProduct(id).price, 0));
  expect(saved.state.furniture.stored.christmasTree).toBe(2);
  expect(saved.state.ownedClothing).toContain('redCape');
  expect(saved.state.ownedFinishes).toContain(FINISH_IDS[0]);
  expect(saved.state.day).toBe(1);
  expect(saved.state.leaves).toBe(0);
  expect(saved.state.stock).toEqual(checkpoint.stock);
  const previous = slot.read();
  expect(() => purchaseChristmasItem(owner, 'redCape')).toThrow();
  expect(slot.read()).toBe(previous);
  expect(getGameState(owner).leaves).toBe(999);
  endCafeDay(owner);
  expect(loadGame(slot.read()!)).toEqual({ ok: true, state: getGameState(owner) });
});

it('saves garden work against the pre-day checkpoint, then resumes and saves the live cafe normally', () => {
  const values = new Map<string, unknown>();
  const owner = { registry: { get: (key: string) => values.get(key), set: (key: string, value: unknown) => values.set(key, value) } } as unknown as Phaser.Game;
  const slot = memorySaveSlot();
  initGameState(owner, slot);
  const beforeDay = skipTutorial(plantCrop(buySeed({ ...createNewGame(), leaves: 20 }, 'mushroom'), 0, 'mushroom'));
  continueGame(owner, beforeDay);
  beginCafeDay(owner); // WorldMap captures day 1 before opening day 2.
  setGameState(owner, startNextDay(beforeDay));
  beginCafeDay(owner); // Floor must keep that checkpoint.
  const live = getGameState(owner);
  setGameState(owner, { ...live, leaves: live.leaves + 8, stock: { ...live.stock, mushroom: 22 } });
  setGardenGameState(owner, tendCrop(getGameState(owner), 0, 1000));
  setGardenGameState(owner, tendCrop(getGameState(owner), 0, 301000));
  const saved = loadGame(slot.read()!);
  expect(saved.ok).toBe(true);
  if (!saved.ok) return;
  expect(saved.state.day).toBe(1);
  expect(saved.state.leaves).toBe(beforeDay.leaves);
  expect(saved.state.stock.mushroom).toBe(34);
  expect(saved.state.garden.plots[0]).toBeNull();
  expect(getGameState(owner).day).toBe(2);
  expect(getGameState(owner).stock.mushroom).toBe(26);
  endCafeDay(owner);
  expect(loadGame(slot.read()!)).toEqual({ ok: true, state: getGameState(owner) });
});

it('immediately saves seasonal packets, planted outcomes and double special harvests during a cafe day', () => {
  const values = new Map<string, unknown>();
  const owner = { registry: { get: (key: string) => values.get(key), set: (key: string, value: unknown) => values.set(key, value) } } as unknown as Phaser.Game;
  const slot = memorySaveSlot();
  initGameState(owner, slot);
  const beforeDay = buySeed({ ...createNewGame(), leaves: 20 }, 'mushroom', 'christmas', 'christmas');
  continueGame(owner, beforeDay);
  beginCafeDay(owner);
  setGameState(owner, { ...beforeDay, day: 2, leaves: 99, stock: { ...beforeDay.stock, mushroom: 1 } });
  setGardenGameState(owner, plantCrop(getGameState(owner), 0, 'mushroom', 'christmas'));
  const planted = loadGame(slot.read()!);
  expect(planted.ok && planted.state.garden.plots[0]?.variant).toBe('christmas');
  expect(planted.ok && planted.state.garden.seasonalSeeds.mushroom).toBe(0);
  setGardenGameState(owner, tendCrop(getGameState(owner), 0, 1000));
  setGardenGameState(owner, tendCrop(getGameState(owner), 0, 301000, 0));
  const saved = loadGame(slot.read()!);
  expect(saved.ok).toBe(true);
  if (!saved.ok) return;
  expect(saved.state.day).toBe(1);
  expect(saved.state.leaves).toBe(15);
  expect(saved.state.stock).toEqual(beforeDay.stock);
  expect(saved.state.garden.harvests.christmas.mushroom).toBe(8);
  expect(saved.state.garden.plots[0]).toBeNull();
  setGardenGameState(owner, sellChristmasCrop(getGameState(owner), 'mushroom', 1));
  const soldOne = getGameState(owner);
  setGardenGameState(owner, sellChristmasCrop(soldOne, 'mushroom', 'all'));
  const exchanged = loadGame(slot.read()!);
  expect(exchanged.ok && exchanged.state.christmasTickets).toBe(8);
  expect(exchanged.ok && exchanged.state.garden.harvests.christmas.mushroom).toBe(0);
  expect(exchanged.ok && exchanged.state.leaves).toBe(15);
  expect(exchanged.ok && exchanged.state.stock).toEqual(beforeDay.stock);
  expect(exchanged.ok && exchanged.state.day).toBe(1);
  const savedText = slot.read();
  setGardenGameState(owner, tendCrop(getGameState(owner), 0, 301000, 0));
  expect(slot.read()).toBe(savedText);
});

