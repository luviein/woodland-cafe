// Import the supplied pouch and regenerate matching native table/packet sprites.
const fs = require('fs'), path = require('path'), os = require('os'), cp = require('child_process');
const P = require('../.claude/skills/pixel-sprites/scripts/pixel.cjs');
const raw = path.join(os.tmpdir(), 'woodland-seed-pouch.rgb');
cp.execFileSync('powershell.exe', ['-ExecutionPolicy', 'Bypass', '-File', '.claude/skills/pixel-sprites/scripts/decode.ps1', 'art-templates/seed-pouch-source.png', raw]);
const img = P.loadRaw(raw, 1536, 1024);
// Remove the brown backdrop while retaining the much darker outline.
const isBg = ([r,g,b]) => r > 45 && r < 115 && g < 75 && b < 70 && r - g > 15;
const boxes = [{x0:138,y0:134,x1:405,y1:439},{x0:1008,y0:612,x1:1279,y1:897}];
const colours = P.palette(P.samplesOf(img, boxes, {isBg}), 18);
const imported = P.toRows(boxes.map(box => P.shrink(img, box, 24, colours, {isBg, outlineShare:0.2}).grid), colours);
const frames = P.fitAll(imported.rows.map(rows => P.outlineEdges(P.fillHoles(P.despeck(rows)))));
const art = { seedPouch: {legend:imported.legend, frames} };
const legend = { o:'#493026', d:'#684232', s:'#916044', h:'#c18a5c', b:'#e2ad72', c:'#ffe0ad', w:'#fff0ca', g:'#526334', l:'#8e9b46', r:'#bb4436', a:'#e8734e' };
const grid = (w,h)=>Array.from({length:h},()=>Array(w).fill('.'));
const rect=(g,x,y,w,h,c)=>{for(let j=y;j<y+h;j++)for(let i=x;i<x+w;i++)if(g[j]?.[i]!==undefined)g[j][i]=c};
const oval=(g,x,y,rx,ry,c)=>{for(let j=y-ry;j<=y+ry;j++)for(let i=x-rx;i<=x+rx;i++)if(((i-x)/rx)**2+((j-y)/ry)**2<=1&&g[j]?.[i]!==undefined)g[j][i]=c};
const rows=g=>g.map(r=>r.join(''));
const table=grid(64,40);
rect(table,7,18,7,21,'o');rect(table,8,19,4,19,'s');rect(table,8,19,1,18,'h');
rect(table,50,18,7,21,'o');rect(table,52,19,4,19,'d');rect(table,52,19,1,18,'h');
rect(table,12,30,40,5,'o');rect(table,13,31,38,2,'s');
rect(table,2,3,60,22,'o');rect(table,4,1,56,24,'o');rect(table,4,3,56,19,'h');
for(let y=4;y<22;y+=6){rect(table,5,y,54,4,'b');rect(table,5,y+4,54,1,'s');rect(table,7,y,50,1,'c');}
rect(table,4,22,56,2,'d');for(const x of [7,55])for(const y of [6,18])rect(table,x,y,2,1,'d');
rect(table,13,8,8,1,'h');rect(table,38,14,12,1,'h');
// A small working table, about one and a half critters wide, in native pixels.
const smallTable=Array.from({length:30},(_,y)=>Array.from({length:48},(_,x)=>table[Math.floor(y*40/30)][Math.floor(x*64/48)]));
art.gardenTable={legend,frames:[P.outlineEdges(rows(smallTable))]};
const flower=grid(16,16);oval(flower,8,8,7,7,'g');for(const[x,y]of[[8,4],[4,8],[12,8],[8,12]])oval(flower,x,y,3,3,'c');oval(flower,8,8,3,3,'h');oval(flower,8,8,2,2,'b');art.seedFlower={legend,frames:[rows(flower)]};
fs.writeFileSync('src/art/sprites/seedPouch.ts',"import type { PixelSprite } from '../pixelSprite';\n\n// Generated by tools/seedPouchArt.cjs; pouch imported from the supplied sheet.\nexport const SEED_POUCH_ART = "+JSON.stringify(art,null,2)+' satisfies Record<string, PixelSprite>;\n');
P.preview(path.join(os.tmpdir(),'seed-pouch-art-review.png'),Object.values(art).flatMap(a=>a.frames.map(rows=>({rows,legend:a.legend}))),{scale:6});
