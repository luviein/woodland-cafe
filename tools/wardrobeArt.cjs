// Rebuild the first clothing set: node tools/wardrobeArt.cjs.
// Redrawn from the supplied Christmas sheet to fit the existing hedgehog.
const fs = require('fs');
const path = require('path');
const P = require('../.claude/skills/pixel-sprites/scripts/pixel.cjs');
const root = path.resolve(__dirname, '..');
const base = P.readSprite(path.join(root, 'src/art/sprites/sheetCritters.ts'), 'HEDGEHOG');
const legend = { ...base.legend, O: '#352522', R: '#bd3f36', S: '#8e302e', H: '#e35a43', C: '#fff0cd', T: '#d9bc91', B: '#47312b', G: '#e9b64d' };
const blank = () => base.frames[0].map(row => [...'.'.repeat(row.length)]);
const stamp = (grid, x, y, rows) => rows.forEach((row, dy) => [...row].forEach((c, dx) => {
  if (c !== '.') grid[y + dy][x + dx] = c;
}));
const flip = grid => grid.map(row => [...row].reverse());
const rows = grid => grid.map(row => row.join(''));

function hat(view) {
  const grid = blank();
  // A connected pompom and continuous cream band avoid the sheet's ragged edges.
  stamp(grid, 5, 0, [
    '........OOOOO......',
    '......OORRRRROO....',
    '.....ORHHHRRRRRO...',
    '....ORHHRRRRRSSRO..',
    '...ORHHRRRRRSSSSRO.',
    '..ORRRRRRRSSSSOOCO.',
    '.OOOOOOOOOOOOOOCCCO',
    'OCCCCCCCCCCCCCOCCCO',
    'OTCCCCCCCCCCCCTOOO.',
    '.OOOOOOOOOOOOO.....',
  ]);
  if (view === 1) {
    // The fold remains on the same physical side when seen from behind.
    return flip(grid);
  }
  if (view === 2 || view === 3) {
    const side = blank();
    stamp(side, 6, 0, [
      '.......OOOOO.....',
      '.....OORRRRROO...',
      '....ORHHRRRRRRO..',
      '...ORHHRRRRSSSRO.',
      '..ORHHRRRRSSSSRO.',
      '.ORRRRRRSSSOOOCO.',
      'OOOOOOOOOOOCCCCCO',
      'OCCCCCCCCCOCCCCCO',
      'OTCCCCCCCCTOOOOO.',
      '.OOOOOOOOOO......',
    ]);
    return view === 3 ? flip(side) : side;
  }
  return grid;
}

function coat(view) {
  const grid = blank();
  if (view < 2) {
    stamp(grid, 7, 20, [
      '....OCCCCCO....',
      '...ORCTCTCRO...',
      '..ORRRRCRRRRO..',
      '.ORHRRRCRRRSRO.',
      'OCRRRRRCRRRRRCO',
      'OCTOBBBGGBBOTCO',
      '.OOORRRGGRROOO.',
      '...OCCCCCCCO...',
      '....OOOOOOO....',
    ]);
    if (view === 1) {
      // Back seam and belt, without a front opening or second buckle.
      for (let y = 22; y <= 24; y++) grid[y][14] = 'R';
      for (let x = 11; x <= 17; x++) grid[25][x] = 'B';
      for (let x = 11; x <= 17; x++) grid[26][x] = 'R';
    }
  } else {
    stamp(grid, 6, 20, [
      '....OCCCCO.....',
      '...OCRRRRRO....',
      '..OCRRHRRRRO...',
      '..ORRRHRSRRRO..',
      '..ORRRCCTRRRO..',
      '..OBBBOOOBBBO..',
      '..ORRRRRRRRRO..',
      '..OCCCCCCCCCO..',
      '...OOOOOOOOO...',
    ]);
    return view === 3 ? flip(grid) : grid;
  }
  return grid;
}

const hats = base.frames.map((_, f) => rows(hat(Math.floor(f / 3))));
const coats = base.frames.map((_, f) => rows(coat(Math.floor(f / 3))));
const equipped = base.frames.map((frame, f) => frame.map((row, y) => [...row].map((c, x) => {
  // Match the original frame exactly, so lifting feet never shifts the outfit.
  return hats[f][y][x] !== '.' ? hats[f][y][x] : coats[f][y][x] !== '.' ? coats[f][y][x] : c;
}).join('')));
const out = path.join(root, 'src/art/sprites/wardrobe.ts');
fs.writeFileSync(out, "import type { PixelSprite } from '../pixelSprite';\n\n// Generated by tools/wardrobeArt.cjs; make touch-ups there.\n" + P.legendTs('LEGEND', legend));
const labels = base.frames.map((_, f) => `${['front', 'back', 'left', 'right'][Math.floor(f / 3)]}, ${['standing', 'step 1', 'step 2'][f % 3]}`);
for (const [name, frames] of [['SANTA_HAT', hats], ['SANTA_COAT', coats], ['HEDGEHOG_SANTA_PREVIEW', equipped]]) {
  P.writeSprite(out, name, frames, { labels });
}
if (process.argv[2]) P.preview(process.argv[2], [base.frames[0], ...[0, 3, 6, 9].map(f => equipped[f])].map(r => ({ rows: r, legend })), { scale: 10, perRow: 5 });
