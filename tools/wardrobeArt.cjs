// Rebuild the first clothing set: node tools/wardrobeArt.cjs.
// Redrawn from the supplied Christmas sheet to fit the existing hedgehog.
const fs = require('fs');
const path = require('path');
const P = require('../.claude/skills/pixel-sprites/scripts/pixel.cjs');
const root = path.resolve(__dirname, '..');
const base = P.readSprite(path.join(root, 'src/art/sprites/sheetCritters.ts'), 'HEDGEHOG');
const legend = { ...base.legend, O: '#352522', R: '#bd3f36', S: '#8e302e', H: '#e35a43', C: '#fff0cd', T: '#d9bc91', B: '#47312b', G: '#e9b64d' };
const blank = () => base.frames[0].map(row => [...'.'.repeat(row.length)]);
const stamp = (grid, x, y, rows) => rows.forEach((row, dy) => [...row].forEach((c, dx) => {
  if (c !== '.') grid[y + dy][x + dx] = c;
}));
const flip = grid => grid.map(row => [...row].reverse());
const rows = grid => grid.map(row => row.join(''));

function fitBrim(grid, view) {
  // The original brim stopped at the hanging pompom. It must continue under
  // it to the far edge of the head, rather than leave a bare forehead strip.
  const left = view < 2 ? 5 : 6, right = view < 2 ? 23 : 22;
  for (let x = left; x <= right; x++) {
    if (grid[6][x] === '.') grid[6][x] = 'O';
    grid[7][x] = x === left || x === right ? 'O' : 'C';
    grid[8][x] = x === left || x === right ? 'O' : x === left + 1 || x === right - 1 ? 'T' : 'C';
    grid[9][x] = x === left || x === right ? '.' : 'O';
  }
  return grid;
}

function hat(view) {
  const grid = blank();
  // A connected pompom and continuous cream band avoid the sheet's ragged edges.
  stamp(grid, 5, 0, [
    '........OOOOO......',
    '......OORRRRROO....',
    '.....ORHHHRRRRRO...',
    '....ORHHRRRRRSSRO..',
    '...ORHHRRRRRSSSSRO.',
    '..ORRRRRRRSSSSOOCO.',
    '.OOOOOOOOOOOOOOCCCO',
    'OCCCCCCCCCCCCCOCCCO',
    'OTCCCCCCCCCCCCTOOO.',
    '.OOOOOOOOOOOOO.....',
  ]);
  if (view === 1) {
    // The fold remains on the same physical side when seen from behind.
    return fitBrim(flip(grid), view);
  }
  if (view === 2 || view === 3) {
    const side = blank();
    stamp(side, 6, 0, [
      '.......OOOOO.....',
      '.....OORRRRROO...',
      '....ORHHRRRRRRO..',
      '...ORHHRRRRSSSRO.',
      '..ORHHRRRRSSSSRO.',
      '.ORRRRRRSSSOOOCO.',
      'OOOOOOOOOOOCCCCCO',
      'OCCCCCCCCCOCCCCCO',
      'OTCCCCCCCCTOOOOO.',
      '.OOOOOOOOOO......',
    ]);
    return fitBrim(view === 3 ? flip(side) : side, view);
  }
  return fitBrim(grid, view);
}

function coat(view, pose = 0) {
  const grid = blank();
  // The quills cover the entire back: painting a coat over them makes it
  // float on the animal's shell. The exposed pale patch is its tail.
  if (view === 1) return grid;
  if (view === 0 || view === 2) {
    const frame = base.frames[view * 3 + pose];
    const fur = new Set('efghijklmnpqrstuv');
    for (let y = 20; y <= 27; y++) {
      const body = [...frame[y]].flatMap((c, x) => fur.has(c) ? [x] : []);
      if (!body.length) continue;
      const left = Math.min(...body), right = Math.max(...body);
      for (const x of body) {
        // Follow the original torso and sleeves instead of stamping a generic
        // jacket across the differently shaped side views and their quills.
        let colour = x <= left + 1 ? 'H' : x >= right - 1 ? 'S' : 'R';
        if (view === 0 && x === 14) colour = 'C';
        if (y === 20 || y === 27) colour = 'C';
        if (y === 25) colour = view === 0 && x >= 13 && x <= 15 ? 'G' : 'B';
        if (view === 0 && y === 24 && (x <= 8 || x >= 20)) colour = 'C';
        if (view === 2 && y === 24 && x <= left + 2) colour = 'C';
        grid[y][x] = colour;
      }
    }
    return grid;
  }
  // Preserve the right view already approved in the running wardrobe.
    stamp(grid, 6, 20, [
      '....OCCCCO.....',
      '...OCRRRRRO....',
      '..OCRRHRRRRO...',
      '..ORRRHRSRRRO..',
      '..ORRRCCTRRRO..',
      '..OBBBOOOBBBO..',
      '..ORRRRRRRRRO..',
      '..OCCCCCCCCCO..',
      '...OOOOOOOOO...',
    ]);
  return flip(grid);
}

const hats = base.frames.map((_, f) => rows(hat(Math.floor(f / 3))));
const coats = base.frames.map((_, f) => rows(coat(Math.floor(f / 3), f % 3)));
const equipped = base.frames.map((frame, f) => frame.map((row, y) => [...row].map((c, x) => {
  // Match the original frame exactly, so lifting feet never shifts the outfit.
  return hats[f][y][x] !== '.' ? hats[f][y][x] : coats[f][y][x] !== '.' ? coats[f][y][x] : c;
}).join('')));
const out = path.join(root, 'src/art/sprites/wardrobe.ts');
fs.writeFileSync(out, "import type { PixelSprite } from '../pixelSprite';\n\n// Generated by tools/wardrobeArt.cjs; make touch-ups there.\n" + P.legendTs('LEGEND', legend));
const labels = base.frames.map((_, f) => `${['front', 'back', 'left', 'right'][Math.floor(f / 3)]}, ${['standing', 'step 1', 'step 2'][f % 3]}`);
for (const [name, frames] of [['SANTA_HAT', hats], ['SANTA_COAT', coats], ['HEDGEHOG_SANTA_PREVIEW', equipped]]) {
  P.writeSprite(out, name, frames, { labels });
}
if (process.argv[2]) P.preview(process.argv[2], [base.frames[0], ...[0, 3, 6, 9].map(f => equipped[f])].map(r => ({ rows: r, legend })), { scale: 10, perRow: 5 });
