// Small native sprites; regeneration preserves the outlines and connected stems.
const fs = require('fs');
const legend = { o: '#493026', d: '#684232', s: '#916044', h: '#b98157', g: '#3e6835', l: '#77a34d', r: '#bb4436', a: '#e8734e', c: '#f5d6a3', w: '#fff0ca' };
function grid(w = 24, h = 24) { return Array.from({ length: h }, () => Array(w).fill('.')); }
function rect(g, x, y, w, h, c) { for (let j=y;j<y+h;j++) for(let i=x;i<x+w;i++) if(g[j]?.[i]!==undefined)g[j][i]=c; }
function oval(g, x, y, rx, ry, c) { for(let j=y-ry;j<=y+ry;j++)for(let i=x-rx;i<=x+rx;i++)if(((i-x)/rx)**2+((j-y)/ry)**2<=1 && g[j]?.[i]!==undefined)g[j][i]=c; }
const rows = g => g.map(r => r.join(''));
const soil = grid(48,32);
rect(soil,2,4,44,26,'o');rect(soil,4,3,40,28,'o');rect(soil,4,5,40,23,'s');rect(soil,6,7,36,19,'d');
for(let y=9;y<25;y+=5){rect(soil,7,y,34,1,'s');rect(soil,8,y+1,32,1,'o');}
rect(soil,4,5,40,1,'h');rect(soil,5,28,38,1,'h');
const art = { gardenSoil: { legend, frames:[rows(soil)] } };
for(const crop of ['mushroom','tomato','chilli']) {
  const frames=[];
  for(let stage=0;stage<4;stage++) {
    const g=grid();
    if(stage===0){oval(g,12,20,4,2,'o');rect(g,10,19,4,2,'h');}
    else if(crop==='mushroom') {
      for(const [x,y,size] of (stage===1?[[12,18,3]]:stage===2?[[12,15,5]]:[[8,17,5],[17,14,5]])) {
        rect(g,x-2,y,5,7,'o');rect(g,x-1,y,3,6,'c');oval(g,x,y,size+1,4,'o');oval(g,x,y-1,size,3,stage===3?'r':'s');rect(g,x-2,y-2,2,1,'c');
      }
    } else {
      const top=stage===1?16:8;
      rect(g,11,top,3,15+(8-top),'o');rect(g,12,top,1,22-top,'g');
      oval(g,8,top+3,4,2,'o');oval(g,8,top+2,3,1,'l');oval(g,17,top+6,4,2,'o');oval(g,17,top+5,3,1,'l');
      if(stage>=2)for(const [x,y] of [[7,14],[17,18]]) {
        if(crop==='tomato'){oval(g,x,y,4,4,'o');oval(g,x,y,3,3,stage===3?'r':'g');rect(g,x-1,y-2,2,1,stage===3?'a':'l');rect(g,x,y-4,1,2,'g');}
        else {rect(g,x-2,y-2,5,6,'o');rect(g,x-1,y-1,3,5,stage===3?'r':'g');rect(g,x,y+4,2,2,'o');rect(g,x,y-3,2,2,'g');}
      }
    }
    frames.push(rows(g));
  }
  art['garden'+crop[0].toUpperCase()+crop.slice(1)]={legend,frames};
}
const door=grid();rect(door,3,0,18,24,'o');rect(door,5,2,14,22,'s');rect(door,6,3,12,1,'h');rect(door,7,5,10,10,'o');rect(door,8,6,8,8,'g');rect(door,10,8,4,1,'l');rect(door,11,7,2,5,'l');rect(door,6,17,12,1,'o');rect(door,15,18,2,2,'c');art.gardenDoor={legend,frames:[rows(door)]};
const fence=grid(32,24);rect(fence,0,9,32,3,'o');rect(fence,0,10,32,1,'h');rect(fence,0,18,32,3,'o');rect(fence,0,19,32,1,'s');for(const x of [3,19]){rect(fence,x,4,7,20,'o');rect(fence,x+1,3,5,20,'s');rect(fence,x+2,4,1,18,'h');}art.gardenFence={legend,frames:[rows(fence)]};
fs.writeFileSync('src/art/sprites/garden.ts',"import type { PixelSprite } from '../pixelSprite';\n\n// Generated by tools/gardenArt.cjs.\nexport const GARDEN_ART = "+JSON.stringify(art,null,2)+' satisfies Record<string, PixelSprite>;\n');
