// Fit the shared Santa outfit to rabbit, mouse and deer. Run after wardrobeArt.cjs.
const fs = require('fs');
const path = require('path');
const P = require('../.claude/skills/pixel-sprites/scripts/pixel.cjs');
const root = path.resolve(__dirname, '..');
const { attachSideHat, attachCoat } = require('./clothingRig.cjs');
const file = path.join(root, 'src/art/sprites/wardrobeCritters.ts');
const shared = P.readSprite(path.join(root, 'src/art/sprites/wardrobe.ts'), 'SANTA_HAT');
const specs = {
  RABBIT: { hats: [[2, 6, 18], [2, 6, 18], [1, 7, 17], [4, 7, 17]], body: [[26, 33, 1, 20], [26, 33, 1, 20], [26, 33, 5, 15], [26, 33, 6, 16]], tail: (v, x, y) => v === 1 && y >= 30 && x >= 8 && x <= 13 },
  MOUSE: { hats: [[4, 3, 18], [4, 2, 18], [2, 1, 19], [5, 0, 19]], body: [[20, 27, 4, 21], [18, 25, 3, 22], [20, 27, 4, 17], [19, 26, 8, 20]], tail: (v, x, y) => v === 1 && y >= 25 && x >= 11 && x <= 14 },
  DEER: { hats: [[5, 5, 19], [4, 5, 19], [5, 5, 17], [5, 5, 17]], body: [[24, 33, 5, 21], [24, 33, 3, 23], [24, 33, 5, 15], [24, 33, 11, 21]], tail: (v, x, y) => v === 1 && y >= 28 && x >= 10 && x <= 16 },
};
fs.writeFileSync(file, "import type { PixelSprite } from '../pixelSprite';\n\n// Generated by tools/wardrobeCritters.cjs: shared style, individual fittings.\n" + P.legendTs('LEGEND', shared.legend));
const previews = [];
for (const [animal, spec] of Object.entries(specs)) {
  const base = P.readSprite(path.join(root, 'src/art/sprites/sheetCritters.ts'), animal);
  const blank = () => base.frames[0].map(row => [...'.'.repeat(row.length)]);
  const hats = [], coats = [], equipped = [];
  for (let f = 0; f < 12; f++) {
    const view = Math.floor(f / 3), frame = base.frames[f];
    let hat = blank();
    // Share the design, but anchor the band to each head's forehead. Ears and
    // antlers above the hat remain the original animal's pixels.
    const source = shared.frames[view * 3];
    const occupied = source.flatMap(row => [...row].flatMap((c, x) => c !== '.' ? [x] : []));
    const min = Math.min(...occupied), max = Math.max(...occupied);
    const [hx, hy, width] = spec.hats[view];
    for (let y = 0; y < 10; y++) for (let x = 0; x < width; x++) {
      hat[hy + y][hx + x] = source[y][min + Math.min(max - min, Math.floor(x * (max - min + 1) / width))];
    }
    if (view >= 2) hat = attachSideHat(source, frame, animal.toLowerCase(), view);
    const coat = attachCoat(frame, spec.body[view], view, { tail: spec.tail });
    // Joining a hat to long ears can enclose a single background pixel.
    // Fill only newly enclosed pixels in the overlay, never the animal art.
    const hatOnBody = frame.map((row, y) => [...row].map((c, x) => hat[y][x] === '.' ? c : hat[y][x]).join(''));
    const sealed = P.fillHoles(hatOnBody, 'O');
    sealed.forEach((row, y) => [...row].forEach((c, x) => { if (c !== hatOnBody[y][x]) hat[y][x] = c; }));
    const hr = hat.map(row => row.join('')), cr = coat.map(row => row.join(''));
    hats.push(hr); coats.push(cr);
    equipped.push(frame.map((row, y) => [...row].map((c, x) => hr[y][x] !== '.' ? hr[y][x] : cr[y][x] !== '.' ? cr[y][x] : c).join('')));
  }
  const labels = base.frames.map((_, f) => `${['front', 'back', 'left', 'right'][Math.floor(f / 3)]}, ${['standing', 'step 1', 'step 2'][f % 3]}`);
  for (const [name, frames] of [[`${animal}_SANTA_HAT`, hats], [`${animal}_SANTA_COAT`, coats], [`${animal}_SANTA_PREVIEW`, equipped]]) P.writeSprite(file, name, frames, { labels });
  previews.push(...[0, 3, 6, 9].map(f => ({ rows: equipped[f], legend: shared.legend })));
}
if (process.argv[2]) P.preview(process.argv[2], previews, { scale: 8, perRow: 4 });
