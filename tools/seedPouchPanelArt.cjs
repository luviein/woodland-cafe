// Retain the supplied frame art, but clear its sample inventory for live UI cards.
const fs=require('fs'),path=require('path'),os=require('os'),cp=require('child_process');
const P=require('../.claude/skills/pixel-sprites/scripts/pixel.cjs');
const raw=path.join(os.tmpdir(),'seed-pouch-panel.rgb');
cp.execFileSync('powershell.exe',['-ExecutionPolicy','Bypass','-File','.claude/skills/pixel-sprites/scripts/decode.ps1','art-templates/seed-pouch-panel-source.png',raw]);
const img=P.loadRaw(raw,1536,1024), box={x0:126,y0:73,x1:1412,y1:938};
const W=240,H=162,step=(box.x1-box.x0)/W;
// Only connected exterior brown is transparent: the carved wood keeps its shadows.
const exterior=new Set(),todo=[];
const background=([r,g,b])=>r>44&&r<120&&g<80&&b<75&&r-g>15;
for(let x=box.x0;x<=box.x1;x++){todo.push([x,box.y0]);todo.push([x,box.y1]);}
for(let y=box.y0;y<=box.y1;y++){todo.push([box.x0,y]);todo.push([box.x1,y]);}
while(todo.length){const[x,y]=todo.pop(),key=y*1536+x;if(x<box.x0||x>box.x1||y<box.y0||y>box.y1||exterior.has(key)||!background(img.px(x,y)))continue;exterior.add(key);todo.push([x-1,y],[x+1,y],[x,y-1],[x,y+1]);}
const samples=P.samplesOf(img,[box],{step:4,isBg:background});
const colours=P.palette(samples,40);
const nearest=c=>{let best=0,score=Infinity;colours.forEach((p,i)=>{const d=p.reduce((n,v,k)=>n+(v-c[k])**2,0);if(d<score){score=d;best=i;}});return best;};
const grid=Array.from({length:H},(_,y)=>Array.from({length:W},(_,x)=>{
  const sx=Math.min(box.x1,Math.floor(box.x0+(x+0.5)*step)),sy=Math.min(box.y1,Math.floor(box.y0+(y+0.5)*step));
  if(exterior.has(sy*1536+sx))return null;
  // Erase the reference's packets, counts, slot lines and scrollbar. Preserve floral corners.
  if(sx>=224&&sx<=1367&&sy>=314&&sy<=823){
    const fade=(sy-314)/(823-314);
    return nearest([255-7*fade,225-9*fade,177-9*fade]);
  }
  return nearest(img.px(sx,sy));
}));
const imported=P.toRows([grid],colours);
const art={seedPouchFrame:{legend:imported.legend,frames:imported.rows}};
// Soft stepped card edges instead of thick dark rectangular button borders.
const legend={o:'#e8ba80',h:'#ffeac5',c:'#ffe2b4',s:'#f5d09c',w:'#fff0d2'};
const card=Array.from({length:74},()=>Array(62).fill('.'));
for(let y=0;y<74;y++)for(let x=0;x<62;x++){
  const inset=y===0||y===73?4:y<3||y>70?2:0;
  if(x<inset||x>=62-inset)continue;
  const edge=y===0||y===73||x===inset||x===61-inset;
  card[y][x]=edge?'o':y<3?'w':y<34?'h':y>70?'s':'c';
}
art.seedPouchCard={legend,frames:[card.map(r=>r.join(''))]};
fs.writeFileSync('src/art/sprites/seedPouchPanel.ts',"import type { PixelSprite } from '../pixelSprite';\n\n// Generated by tools/seedPouchPanelArt.cjs from the supplied panel reference.\nexport const SEED_PANEL_ART = "+JSON.stringify(art,null,2)+' satisfies Record<string, PixelSprite>;\n');
P.preview(path.join(os.tmpdir(),'seed-pouch-frame-review.png'),[{rows:imported.rows[0],legend:imported.legend}],{scale:3});
