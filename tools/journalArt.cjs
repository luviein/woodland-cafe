// Compact fallback grids for the approved PNG overrides; no invented art.
const fs = require('fs');
const P = require('../.claude/skills/pixel-sprites/scripts/pixel.cjs');
const art = {};
for (const job of JSON.parse(fs.readFileSync(process.argv[2], 'utf8'))) {
  const bytes = fs.readFileSync(job.raw), samples = [];
  for (let i = 0; i < bytes.length; i += 16) if (bytes[i + 3] >= 128) samples.push([...bytes.subarray(i, i + 3)]);
  const palette = P.palette(samples, 48, 8);
  const grid = Array.from({ length: job.height }, (_, y) => Array.from({ length: job.width }, (_, x) => {
    const at = (y * job.width + x) * 4;
    if (bytes[at + 3] < 128) return null;
    let best = 0, distance = Infinity;
    palette.forEach((rgb, i) => {
      const d = rgb.reduce((sum, c, channel) => sum + (c - bytes[at + channel]) ** 2, 0);
      if (d < distance) { best = i; distance = d; }
    });
    return best;
  }));
  const converted = P.toRows([grid], palette);
  art[job.name] = { legend: converted.legend, frames: converted.rows };
}
fs.writeFileSync('src/art/sprites/journal.ts', "import type { PixelSprite } from '../pixelSprite';\n\n// Generated by tools/journalArt.ps1 from approved source images.\nexport const JOURNAL_ART = " + JSON.stringify(art) + ' satisfies Record<string, PixelSprite>;\n');
