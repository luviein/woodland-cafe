// Import all supplied packets; adapt the sprout packet for the two existing crops absent from the sheet.
const fs=require('fs'),os=require('os'),path=require('path'),cp=require('child_process');
const P=require('../.claude/skills/pixel-sprites/scripts/pixel.cjs');
const raw=path.join(os.tmpdir(),'woodland-seed-packets.rgb');
cp.execFileSync('powershell.exe',['-ExecutionPolicy','Bypass','-File','.claude/skills/pixel-sprites/scripts/decode.ps1','art-templates/seed-packets-source.png',raw]);
const img=P.loadRaw(raw,1536,1024);
const names=['Carrot','Tomato','Strawberry','Blueberry','Sunflower','Wheat','Daisy','Lavender','Cotton','Sprout'];
const boxes=names.map((_,i)=>({x0:143+i%5*258,y0:i<5?210:540,x1:363+i%5*258,y1:i<5?462:795}));
const isBg=([r,g,b])=>r>47&&r<150&&g<115&&b<105&&r-g>12;
// Brown crop outlines resemble the backdrop. Remove only connected exterior
// background, rather than deleting those colours inside the packet artwork.
const exterior=new Set();
for(const box of boxes){
  const todo=[];
  for(let x=box.x0;x<=box.x1;x++){todo.push([x,box.y0]);todo.push([x,box.y1]);}
  for(let y=box.y0;y<=box.y1;y++){todo.push([box.x0,y]);todo.push([box.x1,y]);}
  while(todo.length){const[x,y]=todo.pop(),key=y*1536+x;
    if(x<box.x0||x>box.x1||y<box.y0||y>box.y1||exterior.has(key)||!isBg(img.px(x,y)))continue;
    exterior.add(key);todo.push([x-1,y],[x+1,y],[x,y-1],[x,y+1]);
  }
}
const clean={...img,px:(x,y)=>exterior.has(y*1536+x)?[0,255,255]:img.px(x,y)};
const transparent=([r,g,b])=>r===0&&g===255&&b===255;
const colours=P.palette(P.samplesOf(clean,boxes,{isBg:transparent}),40);
const converted=P.toRows(boxes.map(box=>P.shrink(clean,box,32,colours,{isBg:transparent,outlineShare:0.12}).grid),colours);
const frames=P.fitAll(converted.rows.map(rows=>P.outlineEdges(P.fillHoles(P.despeck(rows)))));
const art=Object.fromEntries(names.map((name,i)=>['seedPacket'+name,{legend:converted.legend,frames:[frames[i]]}]));
const base=frames[9].map(row=>[...row]);
// Clear only the printed sprout, preserving the supplied packet's fold, crease and outline.
for(let y=12;y<32;y++)for(let x=6;x<28;x++)base[y][x]='8';
const legend={...converted.legend,0:'#38251b',1:'#c94928',2:'#ee7540',3:'#ffbb70',4:'#547136',5:'#879849',6:'#ffdcaa',7:'#d49c64',8:'#ffd09a'};
const rect=(g,x,y,w,h,c)=>{for(let j=y;j<y+h;j++)for(let i=x;i<x+w;i++)g[j][i]=c;};
const oval=(g,x,y,rx,ry,c)=>{for(let j=y-ry;j<=y+ry;j++)for(let i=x-rx;i<=x+rx;i++)if(((i-x)/rx)**2+((j-y)/ry)**2<=1)g[j][i]=c;};
const mushroom=base.map(r=>[...r]);rect(mushroom,14,22,6,8,'0');rect(mushroom,15,22,4,7,'6');rect(mushroom,18,24,1,4,'7');oval(mushroom,16,20,9,6,'0');oval(mushroom,16,19,8,5,'1');oval(mushroom,13,17,3,2,'2');rect(mushroom,11,17,2,2,'6');rect(mushroom,19,20,2,2,'6');
const chilli=base.map(r=>[...r]);rect(chilli,18,13,3,5,'4');rect(chilli,17,13,3,2,'5');
const centres=[18,18,18,18,17,17,16,16,15,14,13,12,11,10],widths=[5,7,8,8,8,7,7,6,6,5,4,3,2,1];
centres.forEach((x,i)=>{const w=widths[i],left=x-Math.floor(w/2);rect(chilli,left,17+i,w,1,'0');if(w>2)rect(chilli,left+1,17+i,w-2,1,'1');if(w>4&&i>0)rect(chilli,left+1,17+i,1,1,'2');});
function outlinedCrop(g){
  // Outline the printed crop on its own layer, not the paper surrounding it.
  const mask=g.map(row=>row.map(c=>/^[0-7]$/.test(c)?c:'.'));
  const outlined=mask.map(row=>[...row]);
  const neighbours=[[1,0],[-1,0],[0,1],[0,-1]];
  mask.forEach((row,y)=>row.forEach((c,x)=>{
    if(c==='.')return;
    const edges=neighbours.filter(([dx,dy])=>(mask[y+dy]?.[x+dx]??'.')==='.');
    if(c==='4'||c==='5')edges.forEach(([dx,dy])=>{if(outlined[y+dy]?.[x+dx]!==undefined)outlined[y+dy][x+dx]='0';});
    else if(edges.length)outlined[y][x]='0';
  }));
  return outlined.map((row,y)=>row.map((c,x)=>c==='.'?g[y][x]:c).join(''));
}
art.seedPacketMushroom={legend,frames:[outlinedCrop(mushroom)]};art.seedPacketChilli={legend,frames:[outlinedCrop(chilli)]};
fs.writeFileSync('src/art/sprites/seedPackets.ts',"import type { PixelSprite } from '../pixelSprite';\n\n// Generated by tools/seedPacketArt.cjs from the supplied packet sheet.\nexport const SEED_PACKET_ART = "+JSON.stringify(art,null,2)+' satisfies Record<string, PixelSprite>;\n');
P.preview(path.join(os.tmpdir(),'seed-packets-import-review.png'),Object.values(art).map(a=>({rows:a.frames[0],legend:a.legend})),{scale:4,columns:5});
